	private void add(String extension, String contentType) {
		extension2ContentType.put(normalize(extension), contentType);
	}

	public String getContentType(String extension) {
		return extension2ContentType.getOrDefault(normalize(extension), "application/octet-stream");
	}

	private static String normalize(String extension) {
		return extension.toLowerCase(Locale.ROOT);
	}
